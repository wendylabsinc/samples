"""Make webcam MJPEG frames browser-decodable.

Many USB UVC webcams emit Motion-JPEG whose frames carry an ``AVI1`` APP0
marker and **omit the Huffman tables** (DHT), relying on the decoder to assume
the standard JPEG example tables. ``libjpeg``-based decoders (Pillow, ffmpeg)
tolerate this, but **browsers refuse to render a JPEG with no DHT** — the
``<img>`` shows a broken-image icon.

We fix it the same way ffmpeg's ``mjpeg2jpeg`` bitstream filter does: when a
frame has no DHT, splice the standard tables in just before the start-of-scan
(SOS) marker, producing a fully standards-compliant baseline JPEG. This is a
cheap byte splice — no decode/re-encode — so the USB path stays "native MJPEG".
"""
