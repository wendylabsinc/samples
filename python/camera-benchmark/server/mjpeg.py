def _table(table_class: int, table_id: int, counts: list[int], values: list[int]) -> bytes:
    assert sum(counts) == len(values), "Huffman counts must match value count"
    return bytes([(table_class << 4) | table_id, *counts, *values])


def _build_dht_segment() -> bytes:
    body = (
        _table(0, 0, _DC_LUMA_COUNTS, _DC_LUMA_VALUES)
        + _table(0, 1, _DC_CHROMA_COUNTS, _DC_CHROMA_VALUES)
        + _table(1, 0, _AC_LUMA_COUNTS, _AC_LUMA_VALUES)
        + _table(1, 1, _AC_CHROMA_COUNTS, _AC_CHROMA_VALUES)
    )
    length = len(body) + 2  # segment length includes the 2 length bytes
    return b"\xff\xc4" + bytes([length >> 8, length & 0xFF]) + body


_STD_DHT_SEGMENT = _build_dht_segment()

_SOS = b"\xff\xda"  # start-of-scan
_DHT = b"\xff\xc4"  # define-huffman-table


def ensure_huffman_tables(jpeg: bytes) -> bytes:
    """Return *jpeg* with standard Huffman tables guaranteed present.

    No-op (returns the input unchanged) when the frame already carries a DHT or
    isn't a JPEG we recognise. Otherwise the standard DHT segment is spliced in
    immediately before the start-of-scan marker.
    """
    sos = jpeg.find(_SOS)
    if sos < 0:
        return jpeg  # no scan marker — not something we can/should rewrite
    if jpeg.find(_DHT, 0, sos) != -1:
        return jpeg  # tables already present (e.g. jpegenc output)
    return jpeg[:sos] + _STD_DHT_SEGMENT + jpeg[sos:]
